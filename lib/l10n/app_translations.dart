  static String translate(String? source, [Locale? locale]) {
    if (source == null || source.isEmpty) return '';
    final activeLocale = locale ?? AppLocaleController.instance.locale;
    if (activeLocale.languageCode != 'hi') return source;

    // Preserve dynamic IDs and counts while translating the fixed labels around them.
    final blockHouse = RegExp(r'^Block (.+?) · House (.+)$').firstMatch(source);
    if (blockHouse != null) {
      return 'ब्लॉक ${blockHouse.group(1)} · मकान ${blockHouse.group(2)}';
    }
    final assignedProgress = RegExp(r'^(\d+) assigned · (\d+) in progress$')
        .firstMatch(source);
    if (assignedProgress != null) {
      return '${assignedProgress.group(1)} सौंपे गए · ${assignedProgress.group(2)} प्रगति पर';
    }
    final openAssigned = RegExp(
      r'^(\d+) open · (\d+) assigned · (\d+) in progress$',
    ).firstMatch(source);
    if (openAssigned != null) {
      return '${openAssigned.group(1)} खुले · ${openAssigned.group(2)} सौंपे गए · ${openAssigned.group(3)} प्रगति पर';
    }
    final showingComplaints = RegExp(r'^Showing (\d+) of (\d+) complaints$')
        .firstMatch(source);
    if (showingComplaints != null) {
      return '${showingComplaints.group(2)} शिकायतों में से ${showingComplaints.group(1)} दिखाई जा रही हैं';
    }

    final upiPayment = RegExp(r'^Pay (.+) using UPI app$').firstMatch(source);
    if (upiPayment != null) {
      return 'UPI ऐप से ${upiPayment.group(1)} का भुगतान करें';
    }

    final direct =
        _hindi[source] ??
        _hindi[source.trim()] ??
        _hindiLower[source.trim().toLowerCase()];
    if (direct != null) return direct;

    for (final entry in _dynamicPrefixes.entries) {
      if (source.startsWith(entry.key)) {
        final suffix = source.substring(entry.key.length);
        return '${entry.value}${_translateStatusSuffix(suffix)}';
      }
    }

    // Translate compact labels compositionally only when every token has a
    // known Hindi equivalent. Never produce half-translated paragraphs.
    final words = RegExp(
      r"[A-Za-z][A-Za-z'/-]*",
      unicode: true,
    ).allMatches(source).toList();
    if (words.isNotEmpty && words.length <= 6) {
      var translated = source;
      for (final word in words.reversed) {
        final raw = word.group(0)!;
        final replacement = _terms[raw] ?? _termsLower[raw.toLowerCase()];
        if (replacement == null) return source;
        translated = translated.replaceRange(word.start, word.end, replacement);
      }
      return translated;
    }
    return source;
  }

  static String _translateStatusSuffix(String value) {
    final trimmed = value.trim();
    final status = _terms[trimmed] ?? _termsLower[trimmed.toLowerCase()];
    return status ?? value;
  }
